import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { bundleText } from '../scripts/bundle.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const NOTICE = '// Generated by scripts/bundle.mjs from src/. Do not edit.';

test('bundleText puts the meta first, then the notice, then the lib, then the body', () => {
  const text = bundleText('M', 'L', 'B');
  assert.ok(text.startsWith('M'));
  const notice = text.indexOf(NOTICE);
  const lib = text.indexOf('L', notice + NOTICE.length);
  const body = text.indexOf('B', lib + 1);
  assert.ok(notice > 0, 'notice line present after the meta');
  assert.ok(lib > notice, 'lib after the notice');
  assert.ok(body > lib, 'body after the lib');
  assert.ok(text.split('\n').includes(NOTICE), 'notice is a line of its own');
});

test('bundle --check exits 0: workflows/ matches src/', () => {
  const r = spawnSync(process.execPath, ['scripts/bundle.mjs', '--check'], { cwd: root, encoding: 'utf8' });
  assert.equal(r.status, 0, r.stderr);
});

test('no generated workflow uses Date, Math.random, imports or require', () => {
  const dir = join(root, 'workflows');
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.js')) : [];
  for (const f of files) {
    const text = readFileSync(join(dir, f), 'utf8');
    assert.doesNotMatch(text, /Date\.now|Math\.random|new Date\(\s*\)|^import |require\(/m, f);
  }
});
