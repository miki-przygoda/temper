#!/usr/bin/env python3
"""A stage's workflow as one script with its args inlined, for args too large to pass.

CLI: python3 scripts/run_script.py <stage> <args.json> <out.js>

It keeps the bundle's meta block first, as the engine requires, and wraps the
rest in `return await (async (args) => {...})(JSON.parse(<text>));`, so the body
runs as it does in the plain bundle and sees the same `args`. The args go in as
JSON text rather than as an object literal: a literal would read a `__proto__`
key as a prototype. Exits 1 (message on stderr), writing nothing, on an unknown
stage or args that aren't a JSON object.
"""
import json
import os
import sys
from pathlib import Path

STAGES = ('build', 'stabilise', 'publish')
NOTICE = '// Generated by scripts/bundle.mjs from src/. Do not edit.'
WORKFLOWS = Path(__file__).resolve().parent.parent / 'workflows'


def split_bundle(text: str):
    """(meta block, everything after the notice line) of a bundled workflow."""
    meta, sep, body = text.partition(NOTICE + '\n')
    if not sep or not meta.startswith('export const meta'):
        raise ValueError('not a bundled workflow: expected the meta block, then the notice line')
    return meta, body


def refuse_constant(name):
    raise ValueError(f'{name} is not JSON')


def read_args(path: str) -> dict:
    with open(path, encoding='utf-8') as f:
        args = json.load(f, parse_constant=refuse_constant)
    if not isinstance(args, dict):
        raise ValueError('args must be a JSON object')
    return args


def script_text(bundle: str, args: dict) -> str:
    meta, body = split_bundle(bundle)
    args_json = json.dumps(args, separators=(',', ':'), allow_nan=False)
    return (
        f'{meta}// Generated by scripts/run_script.py: the bundle with its args inlined. Do not edit.\n'
        f'return await (async (args) => {{\n{body}}})(JSON.parse({json.dumps(args_json)}));\n'
    )


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 3:
        print('usage: run_script.py <stage> <args.json> <out.js>', file=sys.stderr)
        return 1
    stage, args_path, out_path = argv
    if stage not in STAGES:
        print(f"run_script: unknown stage {stage!r}: expected one of {', '.join(STAGES)}", file=sys.stderr)
        return 1
    try:
        args = read_args(args_path)
        text = script_text((WORKFLOWS / f'{stage}.js').read_text(encoding='utf-8'), args)
        out = Path(out_path)
        out.parent.mkdir(parents=True, exist_ok=True)
        tmp = out.with_name(out.name + '.tmp')
        tmp.write_text(text, encoding='utf-8')
        os.replace(tmp, out)
    except (OSError, ValueError) as exc:
        print(f'run_script: args or files could not be used: {exc}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
