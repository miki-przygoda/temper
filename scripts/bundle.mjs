// Bundles each stage's workflow from src/: meta, a notice line, the shared lib, then the body.
// Usage: node scripts/bundle.mjs [--check]
//   --check  writes nothing; exits 1 if any workflows/<stage>.js differs from what it would write.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const STAGES = ['build', 'stabilise', 'publish'];
export const NOTICE = '// Generated by scripts/bundle.mjs from src/. Do not edit.';

const withNewline = (s) => (s.endsWith('\n') ? s : s + '\n');

export function bundleText(metaText, libText, bodyText) {
  return withNewline(metaText) + NOTICE + '\n' + withNewline(libText) + withNewline(bodyText);
}

export function bundleAll(root, { check = false } = {}) {
  const differing = [];
  const read = (p) => readFileSync(join(root, p), 'utf8');
  for (const stage of STAGES) {
    const metaPath = `src/${stage}.meta.js`;
    if (!existsSync(join(root, metaPath))) continue;
    const out = `workflows/${stage}.js`;
    const text = bundleText(read(metaPath), read('src/lib.js'), read(`src/${stage}.js`));
    const outPath = join(root, out);
    const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : null;
    if (current === text) continue;
    differing.push(out);
    if (!check) {
      mkdirSync(dirname(outPath), { recursive: true });
      writeFileSync(outPath, text);
    }
  }
  return differing;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const check = process.argv.includes('--check');
  const differing = bundleAll(root, { check });
  if (check && differing.length) {
    for (const f of differing) console.error(`out of date: ${f} (run node scripts/bundle.mjs)`);
    process.exit(1);
  }
  for (const f of check ? [] : differing) console.log(`wrote ${f}`);
}
